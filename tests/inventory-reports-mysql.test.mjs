import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { randomBytes, randomUUID } from 'node:crypto';
const run = (name, fn) => test(name, { skip: process.env.DRAC_USAGE_TEST_MYSQL_PORT ? false : 'Requires disposable DRAC_USAGE_TEST_MYSQL_PORT' }, fn);
const ok = result => { assert.equal(result.success, true, result.message); return result.data; };
function fixture(t) {
  const db = `drac_usage_test_reports_${process.pid}_${randomBytes(4).toString('hex')}`;
  const call = input => JSON.parse(execFileSync('php', ['tests/fixtures/item-usage-mysql.php', db, JSON.stringify(input)], { encoding: 'utf8' }));
  const today = ok(call({ op: 'init' })).today;
  t.after(() => call({ op: 'drop' }));
  const sql = (sql, params = []) => ok(call({ op: 'sql', sql, params }));
  const report = (id, query = {}, extra = {}) => call({ endpoint: 'inventory-reports', id, query, ...extra });
  const movement = (id, item, source, destination, qty, cost, type, at) => sql('INSERT INTO stock_movements(id,item_id,source_warehouse_id,destination_warehouse_id,quantity,unit_cost,movement_type,reference_type,reference_number,notes,occurred_at) VALUES(?,?,?,?,?,?,?,?,?,?,?)', [id,item,source,destination,qty,cost,type,'opening_balance',id,'Pengujian',at]);
  return { call, sql, today, report, movement };
}
run('balances keep negative and positive warehouses separate and include zero stock', t => {
  const f = fixture(t);
  f.sql("UPDATE warehouse_stocks SET quantity=-2 WHERE warehouse_id='W1' AND item_id='I1'");
  const data = ok(f.report('balances', { branchId: 'ALL' }));
  const rows = data.rows.filter(row => row.itemId === 'I1');
  assert.equal(rows.find(row => row.warehouseId === 'W1').quantity, -2);
  assert.equal(rows.find(row => row.warehouseId === 'W2').quantity, 9);
  assert.equal(data.rows.find(row => row.itemId === 'I2' && row.warehouseId === 'W2').quantity, 0);
  assert.equal(data.rows.find(row => row.itemId === 'I1' && row.warehouseId === 'W1').averageCost, 150000);
});
run('report permission and branch scope are enforced; employee JSON never contains cost fields', t => {
  const f = fixture(t);
  assert.equal(f.report('balances', {}, { user: 'staff' }).status, 403);
  f.sql("UPDATE roles SET permissions='[\"report:view\"]' WHERE id='STAFF'");
  const staff = ok(f.report('balances', {}, { user: 'staff' }));
  assert.equal(staff.canViewCosts, false);
  assert.ok(staff.rows.length > 0);
  assert.ok(staff.rows.every(row => row.branchId === 'B1'));
  assert.ok(staff.rows.every(row => !('averageCost' in row) && !('inventoryValue' in row) && !('purchasePrice' in row)));
  assert.equal(f.report('balances', { branchId: 'B2' }, { user: 'staff' }).status, 403);
  assert.equal(f.report('balances', { warehouseId: 'W2' }, { user: 'staff' }).status, 403);
  assert.equal(f.report('balances', {}, { method: 'POST' }).status, 405);
  const zero = ok(f.report('balances', { branchId: '0' }, { user: 'zero' }));
  assert.ok(zero.rows.length > 0);
  assert.ok(zero.rows.every(row => row.branchId === '0'));
});
